// Writes src/app/data/reference-stats.json from the MADE-UP affinity function (src/worker/synthetic.ts), so the app, the
// Worker and the e2e run offline. Nothing here is Qloo data. `npm run qloo:reference` replaces it with the real aggregates.
import { writeFileSync } from "node:fs";
import { bundleScore } from "../src/app/score";
import { activeLibrary } from "../src/app/themes/ids";
import { populationSd, mean, mulberry32 } from "../src/study/stats";
import { syntheticAffinity } from "../src/worker/synthetic";

const rand = mulberry32(20261015);
const points = Array.from({ length: 40 }, () => ({ lon: -122 + rand() * 52, lat: 26 + rand() * 22 }));
const themes: Record<string, { n: number; mean: number; sd: number }> = {};
for (const t of activeLibrary({}, true)) {
  const scores = points.flatMap((p) => {
    const s = bundleScore(t.entities.map((e) => syntheticAffinity(e.id, p.lon, p.lat)));
    return s === null ? [] : [s];
  });
  themes[t.id] = { n: scores.length, mean: Number(mean(scores).toFixed(5)), sd: Number(populationSd(scores).toFixed(5)) };
}
const out = {
  synthetic: true,
  note: "PLACEHOLDER. Generated by `npm run reference:synthetic` from a made-up affinity function, not from Qloo. `npm run qloo:reference` overwrites this file with real per-theme aggregates (n, mean, SD) from the 40-market reference set.",
  markets: 40,
  pulledAt: null,
  themes,
};
writeFileSync(new URL("../src/app/data/reference-stats.json", import.meta.url), JSON.stringify(out, null, 2) + "\n");
console.log(`wrote synthetic reference for ${Object.keys(themes).length} themes`);
